import { useEffect, useRef, useState } from 'react';
import type {
  Clip,
  CommentResponse,
  HighlightRequest,
  HighlightResponse,
  SmartStats,
} from '@/utils/messages';
import { DEFAULT_SHORTCUTS, shortcutsFrom, tooltip, type Shortcuts } from '@/utils/shortcuts';
import './App.css';

type Notice = { kind: 'error' | 'info' | 'success'; text: string } | null;

const fmt = (sec: number) => {
  const s = Math.max(0, Math.floor(sec));
  const h = Math.floor(s / 3600);
  const m = Math.floor((s % 3600) / 60);
  const ss = String(s % 60).padStart(2, '0');
  return h ? `${h}:${String(m).padStart(2, '0')}:${ss}` : `${m}:${ss}`;
};

const pct = (x: number) => `${Math.round(x * 100)}%`;

/** MM:SS (or H:MM:SS past an hour) – the format YouTube links in comments. */
const stamp = (sec: number) => {
  const s = Math.max(0, Math.floor(sec));
  const h = Math.floor(s / 3600);
  const mm = String(Math.floor((s % 3600) / 60)).padStart(2, '0');
  const ss = String(s % 60).padStart(2, '0');
  return h ? `${h}:${mm}:${ss}` : `${mm}:${ss}`;
};

const WATERMARK = '- Generated by HeatReel';
const COMMENT_HEADER = 'These are the most viewed moments:\n\n';

function timestampsText(clips: Clip[], videoId: string | null) {
  const lines = clips.map((c) => {
    const range = `${stamp(c.start)} - ${stamp(c.end)}`;
    return videoId ? `${range} (https://youtu.be/${videoId}?t=${Math.floor(c.start)})` : range;
  });
  return `${lines.join('\n')}\n\n${WATERMARK}`;
}

/** Emoji tier for a clip's peak heat score (0..1). */
function heatEmoji(peak: number) {
  if (peak >= 0.85) return '🔥';
  if (peak >= 0.7) return '📈';
  return '🎬';
}

/**
 * One line per clip, e.g.
 *   These are the most viewed moments:
 *
 *   🎬 04:38 - 05:12
 *   🔥 11:24 - 11:57
 *
 *   - Generated by HeatReel
 */
function commentText(clips: Clip[], withEmojis: boolean) {
  const lines = clips.map((c) => {
    const range = `${stamp(c.start)} - ${stamp(c.end)}`;
    return withEmojis ? `${heatEmoji(c.intensity)} ${range}` : range;
  });
  return `${COMMENT_HEADER}${lines.join('\n')}\n\n${WATERMARK}`;
}

const NOT_WATCH_PAGE = 'Open a YouTube video, and HeatReel will find its best moments.';

async function send<R extends HighlightResponse | CommentResponse = HighlightResponse>(
  msg: HighlightRequest,
): Promise<R> {
  const fail = (message: string, error = 'UNKNOWN') => ({ ok: false, error, message }) as unknown as R;
  const [tab] = await browser.tabs.query({ active: true, currentWindow: true });
  if (tab?.id == null) return fail('We couldn’t find an active tab.');
  if (tab.url && !/^https?:\/\/([^/]+\.)?youtube\.com\/watch/.test(tab.url)) {
    return fail(NOT_WATCH_PAGE, 'NOT_WATCH_PAGE');
  }
  try {
    const res = (await browser.tabs.sendMessage(tab.id, msg)) as R | undefined;
    return res ?? fail('The page didn’t respond. Try refreshing it.');
  } catch (err) {
    const text = err instanceof Error ? err.message : String(err);
    if (/Receiving end does not exist|Could not establish connection/i.test(text)) {
      return fail(
        'HeatReel isn’t connected to this tab yet. Refresh the YouTube page and try again.',
        'NOT_CONNECTED',
      );
    }
    console.error('[HeatReel] popup message failed', err);
    return fail('Something went wrong talking to the page. Try refreshing it.');
  }
}

function describeStats(stats?: SmartStats) {
  if (!stats) return '';
  switch (stats.method) {
    case 'mean+sd':
      return `Picked moments above ${pct(stats.threshold)} heat (average ${pct(stats.mean)} + ${pct(stats.sd)} spread)`;
    case 'percentile':
      return `This video’s heatmap is pretty even, so we picked its top 15% of moments`;
    case 'custom':
      return `Playing every moment above your ${pct(stats.threshold)} threshold`;
  }
}

/** Reads the shortcuts actually assigned (users can change them). */
function useShortcuts(): Shortcuts {
  const [keys, setKeys] = useState<Shortcuts>(DEFAULT_SHORTCUTS);
  useEffect(() => {
    browser.commands
      ?.getAll()
      .then((cmds) => setKeys(shortcutsFrom(cmds)))
      .catch(() => {});
  }, []);
  return keys;
}

function App() {
  const keys = useShortcuts();

  // Manual overrides
  const [count, setCount] = useState(5);
  const [seconds, setSeconds] = useState(8);
  const [threshold, setThreshold] = useState(''); // percent, '' = none
  const thresholdSet = threshold.trim() !== '' && Number(threshold) > 0;

  const [busy, setBusy] = useState(false);
  const [running, setRunning] = useState(false);
  const [clips, setClips] = useState<Clip[]>([]);
  const [current, setCurrent] = useState(-1);
  const [stats, setStats] = useState<SmartStats | undefined>();
  const [videoId, setVideoId] = useState<string | null>(null);
  const [notice, setNotice] = useState<Notice>(null);
  /** Gentle, non-error hint when the tab can't run a reel (e.g. not a video page). */
  const [pageHint, setPageHint] = useState<string | null>(null);

  // Clip actions
  const [includeLinks, setIncludeLinks] = useState(false);
  const [withEmojis, setWithEmojis] = useState(true);
  const [copied, setCopied] = useState(false);
  const [confirmPost, setConfirmPost] = useState(false);
  const [posting, setPosting] = useState(false);
  const copyTimer = useRef<ReturnType<typeof setTimeout> | undefined>(undefined);
  const confirmTimer = useRef<ReturnType<typeof setTimeout> | undefined>(undefined);

  useEffect(
    () => () => {
      clearTimeout(copyTimer.current);
      clearTimeout(confirmTimer.current);
    },
    [],
  );

  const apply = (res: HighlightResponse) => {
    if (res.ok) {
      setRunning(res.running);
      setClips(res.clips);
      setCurrent(res.current);
      setStats(res.stats);
      setVideoId(res.videoId ?? null);
      setPageHint(null);
    } else {
      setNotice({ kind: 'error', text: res.message });
    }
  };

  // Reflect a reel that's already playing, and keep the status fresh.
  useEffect(() => {
    let alive = true;
    const poll = async () => {
      const res = await send({ type: 'GET_STATUS' });
      if (!alive) return;
      if (res.ok) apply(res);
      else if (res.error === 'NOT_WATCH_PAGE' || (res.error as string) === 'NOT_CONNECTED') {
        setPageHint(res.message);
      }
    };
    poll();
    const id = setInterval(poll, 1000);
    return () => {
      alive = false;
      clearInterval(id);
    };
  }, []);

  const start = async (msg: HighlightRequest) => {
    setBusy(true);
    setNotice({ kind: 'info', text: 'Finding the best moments…' });
    const res = await send(msg);
    setBusy(false);
    if (res.ok) {
      apply(res);
      setNotice(null);
    } else {
      setRunning(false);
      apply(res);
    }
  };

  const startSmart = () => start({ type: 'START_HIGHLIGHTS', mode: 'smart' });

  const startManual = () => {
    const t = threshold.trim() === '' ? undefined : Number(threshold) / 100;
    if (t !== undefined && !(t >= 0 && t <= 1)) {
      setNotice({ kind: 'error', text: 'The threshold should be a number between 0 and 100.' });
      return;
    }
    start({ type: 'START_HIGHLIGHTS', mode: 'manual', count, seconds, minHeatThreshold: t });
  };

  const control = async (type: 'STOP_HIGHLIGHTS' | 'NEXT_CLIP' | 'PREV_CLIP') => {
    setBusy(true);
    const res = await send({ type });
    setBusy(false);
    apply(res);
    if (res.ok) setNotice(null);
  };

  const copyTimestamps = async () => {
    try {
      await navigator.clipboard.writeText(timestampsText(clips, includeLinks ? videoId : null));
      setCopied(true);
      clearTimeout(copyTimer.current);
      copyTimer.current = setTimeout(() => setCopied(false), 2000);
    } catch {
      setNotice({ kind: 'error', text: 'We couldn’t copy to your clipboard. Try once more?' });
    }
  };

  // Posting is public, so it takes two clicks.
  const postToComments = async () => {
    if (!confirmPost) {
      setConfirmPost(true);
      clearTimeout(confirmTimer.current);
      confirmTimer.current = setTimeout(() => setConfirmPost(false), 4000);
      return;
    }
    clearTimeout(confirmTimer.current);
    setConfirmPost(false);
    setPosting(true);
    setNotice({ kind: 'info', text: 'Posting your highlights…' });
    const res = await send<CommentResponse>({
      type: 'POST_COMMENT',
      text: commentText(clips, withEmojis),
    });
    setPosting(false);
    setNotice({ kind: res.ok ? 'success' : 'error', text: res.message });
  };

  const openShortcuts = () => {
    browser.tabs.create({ url: 'chrome://extensions/shortcuts' });
  };

  const clampInt = (v: string, min: number, max: number, fallback: number) => {
    const n = Math.floor(Number(v));
    return Number.isFinite(n) ? Math.min(max, Math.max(min, n)) : fallback;
  };

  const clip = clips[current];
  const startKey = keys['start-smart-reel'];
  const canStart = !busy && !running && !pageHint;

  return (
    <main className="popup">
      <header className="brand">
        <span className="logo" aria-hidden>
          🔥
        </span>
        <h1>HeatReel</h1>
        {running && <span className="live">Playing</span>}
      </header>

      {running && clip ? (
        <section className="now-playing" aria-live="polite">
          <div className="np-title">
            Highlight {current + 1} of {clips.length}
          </div>
          <div className="np-time">
            {fmt(clip.start)} – {fmt(clip.end)}
          </div>
          <div className="transport">
            <button
              className="icon"
              onClick={() => control('PREV_CLIP')}
              disabled={busy}
              title={tooltip('prev-highlight', keys)}
              aria-label="Previous highlight"
            >
              ⏮
            </button>
            <button
              className="stop"
              onClick={() => control('STOP_HIGHLIGHTS')}
              disabled={busy}
              title={tooltip('stop-reel', keys)}
            >
              ■ Stop
            </button>
            <button
              className="icon"
              onClick={() => control('NEXT_CLIP')}
              disabled={busy}
              title={tooltip('next-highlight', keys)}
              aria-label="Next highlight"
            >
              ⏭
            </button>
          </div>
        </section>
      ) : (
        <section className="hero">
          <button
            className="hero-btn"
            onClick={startSmart}
            disabled={!canStart}
            title={tooltip('start-smart-reel', keys)}
          >
            <span className="hero-label">▶ Start Smart Reel</span>
            {startKey && <kbd className="kbd-hint">{startKey}</kbd>}
          </button>
          <p className="hero-sub">Automatically finds &amp; plays the most replayed moments.</p>
        </section>
      )}

      {notice ? (
        <p className={`notice ${notice.kind}`} role={notice.kind === 'error' ? 'alert' : 'status'}>
          {notice.text}
        </p>
      ) : pageHint ? (
        <p className="notice hint">{pageHint}</p>
      ) : stats ? (
        <p className="stats">{describeStats(stats)}</p>
      ) : !running && clips.length ? (
        <p className="stats">
          All done! You watched {clips.length} highlight{clips.length === 1 ? '' : 's'}.
        </p>
      ) : null}

      {clips.length > 0 && (
        <section className="clips">
          <h2>Your highlights</h2>
          <ol>
            {clips.map((c, i) => (
              <li key={`${c.start}-${i}`} className={running && i === current ? 'active' : ''}>
                <span className="idx">{i + 1}</span>
                <span className="range">
                  {stamp(c.start)} – {stamp(c.end)}
                </span>
                <span className="heat" aria-label={`Heat ${pct(c.intensity)}`}>
                  <span style={{ width: pct(c.intensity) }} />
                </span>
              </li>
            ))}
          </ol>

          <div className="share">
            <div className="share-row">
              <button className="secondary" onClick={copyTimestamps}>
                {copied ? '✅ Copied!' : '📋 Copy Timestamps'}
              </button>
              <label className="check" title={videoId ? '' : 'Video ID not available'}>
                <input
                  type="checkbox"
                  checked={includeLinks}
                  disabled={!videoId}
                  onChange={(e) => setIncludeLinks(e.target.checked)}
                />
                Include links
              </label>
            </div>
            <div className="share-row">
              <button
                className={`secondary${confirmPost ? ' confirm' : ''}`}
                onClick={postToComments}
                disabled={posting}
                title="Posts your highlights publicly as a comment on this video"
              >
                {posting ? 'Posting…' : confirmPost ? 'Click again to post' : '💬 Post to Comments'}
              </button>
              <label className="check">
                <input
                  type="checkbox"
                  checked={withEmojis}
                  onChange={(e) => setWithEmojis(e.target.checked)}
                />
                With emojis 🔥
              </label>
            </div>
          </div>
        </section>
      )}

      <details className="advanced">
        <summary>⚙️ Manual Controls &amp; Settings</summary>
        <div className="fields">
          <label className={thresholdSet ? 'ignored' : ''}>
            <span>Number of highlights</span>
            <input
              type="number"
              min={1}
              max={50}
              value={count}
              disabled={running || busy || thresholdSet}
              onChange={(e) => setCount(clampInt(e.target.value, 1, 50, 5))}
            />
          </label>
          <label className={thresholdSet ? 'ignored' : ''}>
            <span>Seconds per highlight</span>
            <input
              type="number"
              min={1}
              max={600}
              value={seconds}
              disabled={running || busy || thresholdSet}
              onChange={(e) => setSeconds(clampInt(e.target.value, 1, 600, 8))}
            />
          </label>
          <label>
            <span>
              Min. heat threshold <small>% · optional</small>
            </span>
            <input
              type="number"
              min={0}
              max={100}
              placeholder="—"
              value={threshold}
              disabled={running || busy}
              onChange={(e) => setThreshold(e.target.value)}
            />
          </label>
          {thresholdSet && (
            <p className="field-hint">
              We’ll play every moment above {Number(threshold)}% heat, so the count and length
              above don’t apply.
            </p>
          )}
        </div>
        <button
          className="secondary wide"
          onClick={startManual}
          disabled={!canStart}
          title="Start a reel using the settings above"
        >
          Start Highlights
        </button>
        <button className="link" onClick={openShortcuts}>
          ⌨️ Customize Shortcuts
        </button>
      </details>
    </main>
  );
}

export default App;
